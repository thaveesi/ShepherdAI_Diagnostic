"""The AI agent apps the scan recognises, and how to recognise each one (``data/apps.json``).

Each entry lists detection anchors (macOS app bundle ids and names, commands, folders in the
home folder, editor and browser extension ids), the discovery reader that reads the app's
settings if there is one, and fixed descriptions from the app's published features. The file
is generated by ``tools/build_app_catalog.py``.
"""

from functools import cache
from importlib import resources
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

AppKind = Literal["assistant", "coding", "browser", "computer", "local models"]
Control = Literal["browser", "computer"]


class AppEntry(BaseModel):
    """One AI agent app and how to recognise it."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    id: str
    name: str
    kind: AppKind
    agent: str | None = None
    mac_bundle_ids: tuple[str, ...] = ()
    mac_app_names: tuple[str, ...] = ()
    binaries: tuple[str, ...] = ()
    folders: tuple[str, ...] = ()
    editor_extensions: tuple[str, ...] = ()
    browser_extensions: tuple[str, ...] = ()
    runs_commands: bool = False
    control: Control | None = None
    can_do: str | None = None
    kept_elsewhere: str | None = None
    credential_files: tuple[tuple[str, str], ...] = Field(default=())


class AppList(BaseModel):
    """The shipped app list file."""

    model_config = ConfigDict(extra="forbid")

    version: Literal[1]
    apps: tuple[AppEntry, ...]


@cache
def load_apps() -> tuple[AppEntry, ...]:
    """The apps shipped with the scanner.

    Raises:
        pydantic.ValidationError: If the shipped file does not have the expected shape.
    """
    text = resources.files("shepherd_scan").joinpath("data/apps.json").read_text(encoding="utf-8")
    return AppList.model_validate_json(text).apps
